#!/usr/bin/env bash
# Add (or reset the password of) a GigaFinance user, run as root:
#   deploy/add-user.sh <login>            # asks for a password
#   deploy/add-user.sh --remove <login>
# Each user gets an own dsh instance: profile, sessions and workspace under
# /var/lib/gigafinance/users/<login>, a free port from 8801, and a login in
# nginx basic auth.
set -euo pipefail

MAP=/etc/nginx/gigafinance-users.map
HTPASSWD=/etc/nginx/gigafinance.htpasswd
USERS=/var/lib/gigafinance/users
SECRETS=/etc/gigafinance/secrets.env

if [ "${1:-}" = "--remove" ]; then
  login="${2:?login}"
  systemctl disable --now "gigafinance@$login" || true
  htpasswd -D "$HTPASSWD" "$login" || true
  sed -i "/^$login /d" "$MAP"
  nginx -t && systemctl reload nginx
  echo "Removed $login (data kept in $USERS/$login)."
  exit 0
fi

login="${1:?usage: add-user.sh <login>}"
[[ "$login" =~ ^[a-z][a-z0-9_-]{1,31}$ ]] || { echo "login: a-z, 0-9, _ or -, starting with a letter"; exit 1; }
# shellcheck disable=SC1090
set -a; . "$SECRETS"; set +a
[ -n "${MOEX_MCP_TOKEN:-}" ] || { echo "Fill MOEX_MCP_TOKEN in $SECRETS first"; exit 1; }

home="$USERS/$login"
if grep -q "^$login " "$MAP"; then
  port=$(awk -v u="$login" '$1==u {gsub(";","",$2); print $2}' "$MAP")
else
  port=8801
  while grep -q " $port;" "$MAP"; do port=$((port + 1)); done
  echo "$login $port;" >> "$MAP"
fi

mkdir -p "$home/dsh/profiles/web" "$home/workspace"
cat > "$home/instance.env" <<EOF
GF_PORT=$port
DSH_HOME=$home/dsh
HOME=$home
EOF
ln -sf "$SECRETS" "$home/dsh/.env"

cat > "$home/dsh/profiles/web/cordis.patch.yml" <<EOF
# Generated by deploy/add-user.sh — contains the MCP token, do not commit.
- insert:
    - id: mcp-moex-finance
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: moex-finance
        transport: streamable-http
        url: $MOEX_MCP_URL
        headers:
          Authorization: Bearer $MOEX_MCP_TOKEN
        toolCallTimeoutMs: 120000
    - id: portfolio-context
      name: '@deepseek-ai/dsh-tool-broker-report/context'

- id: llm-pi-ai
  config:
    providers:
      claude:
        displayName: Claude
        api: anthropic-messages
        baseURL: https://strivershop.ru/claude
        apiKeyEnv: STRIVERSHOP_CLAUDE_API_KEY
        models:
          - id: claude-sonnet-5-5
            name: Claude Sonnet 5.5
          - id: claude-opus-5-5
            name: Claude Opus 5.5
          - id: claude-haiku-5-5
            name: Claude Haiku 5.5
EOF
chmod 600 "$home/dsh/profiles/web/cordis.patch.yml"
chown -R gigafinance:gigafinance "$home"

if [ -n "${GF_PASSWORD:-}" ]; then
  htpasswd -bB "$HTPASSWD" "$login" "$GF_PASSWORD"
else
  htpasswd -B "$HTPASSWD" "$login"
fi
systemctl enable "gigafinance@$login"
systemctl restart "gigafinance@$login"
nginx -t && systemctl reload nginx
echo "User $login ready on port $port."
