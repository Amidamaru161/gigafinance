#!/usr/bin/env bash
# Add a GigaFinance user, or reset their password (run as root):
#   deploy/add-user.sh <login>            # asks for a password (or $GF_PASSWORD)
#   deploy/add-user.sh --remove <login>
# Each user gets an own dsh instance: profile, sessions and workspace under
# /var/lib/gigafinance/users/<login> and a free port from 8801. Logins live in
# /var/lib/gigafinance/auth/users.json (scrypt hashes), served by deploy/auth/server.mjs.
set -euo pipefail

APP=/opt/gigafinance
USERS=/var/lib/gigafinance/users
SECRETS=/etc/gigafinance/secrets.env
ACCOUNTS=/var/lib/gigafinance/auth/users.json
AUTH="sudo -u gigafinance -E /usr/bin/node $APP/deploy/auth/server.mjs"

port_of() {
  [ -f "$ACCOUNTS" ] && node -e "const u=require('$ACCOUNTS')['$1']; if(u) console.log(u.port)" || true
}

if [ "${1:-}" = "--remove" ]; then
  login="${2:?login}"
  systemctl disable --now "gigafinance@$login" || true
  $AUTH remove-user "$login"
  echo "Removed $login (data kept in $USERS/$login)."
  exit 0
fi

login="${1:?usage: add-user.sh <login>}"
[[ "$login" =~ ^[a-z][a-z0-9_-]{1,31}$ ]] || { echo "login: a-z, 0-9, _ or -, starting with a letter"; exit 1; }
# shellcheck disable=SC1090
set -a; . "$SECRETS"; set +a
[ -n "${MOEX_MCP_TOKEN:-}" ] || { echo "Fill MOEX_MCP_TOKEN in $SECRETS first"; exit 1; }

home="$USERS/$login"
port=$(port_of "$login")
if [ -z "$port" ]; then
  used=$(node -e "try{console.log(Object.values(require('$ACCOUNTS')).map(u=>u.port).join(' '))}catch{}")
  port=8801
  while [[ " $used " == *" $port "* ]]; do port=$((port + 1)); done
fi

mkdir -p "$home/dsh/profiles/web" "$home/workspace"
cat > "$home/instance.env" <<EOF
GF_PORT=$port
DSH_HOME=$home/dsh
HOME=$home
EOF
ln -sf "$SECRETS" "$home/dsh/.env"
if [ -n "${DEEPSEEK_API_KEY:-}" ]; then
  printf 'DEEPSEEK_API_KEY: %s\n' "$DEEPSEEK_API_KEY" > "$home/dsh/.credentials.yaml"
  chmod 600 "$home/dsh/.credentials.yaml"
fi

cat > "$home/dsh/profiles/web/cordis.patch.yml" <<EOF
# Generated by deploy/add-user.sh — contains the MCP token, do not commit.
- insert:
    - id: mcp-moex-finance
      name: '@deepseek-ai/dsh-mcp-client'
      config:
        serverName: moex-finance
        transport: streamable-http
        url: $MOEX_MCP_URL
        headers:
          Authorization: Bearer $MOEX_MCP_TOKEN
        toolCallTimeoutMs: 120000
    - id: portfolio-context
      name: '@deepseek-ai/dsh-tool-broker-report/context'

- id: llm-pi-ai
  config:
    providers:
      claude:
        displayName: Claude
        api: anthropic-messages
        baseURL: https://strivershop.ru/claude
        apiKeyEnv: STRIVERSHOP_CLAUDE_API_KEY
        models:
          - id: claude-sonnet-5-5
            name: Claude Sonnet 5.5
          - id: claude-opus-5-5
            name: Claude Opus 5.5
          - id: claude-haiku-5-5
            name: Claude Haiku 5.5
EOF
chmod 600 "$home/dsh/profiles/web/cordis.patch.yml"
chown -R gigafinance:gigafinance "$home"

$AUTH set-user "$login" "$port"
systemctl enable "gigafinance@$login"
systemctl restart "gigafinance@$login"

# Register the user's workspace so the first chat can start right away (idempotent).
for _ in $(seq 1 30); do
  curl -s -m10 -X POST -H "Host: localhost:$port" -H 'content-type: application/json' \
    -d "{\"type\":\"client-request\",\"rpcId\":\"setup\",\"method\":\"workspace.create\",\"payload\":{\"path\":\"$home/workspace\"}}" \
    "http://127.0.0.1:$port/api/workspace.create" | grep -q '"ok":true' && break
  sleep 1
done
echo "User $login ready on port $port."
